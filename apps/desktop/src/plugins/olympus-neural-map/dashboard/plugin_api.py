"""
Olympus Neural Map Plugin API
Serves the olimpo.json graph data generated by MNEMOS cron.
"""

import json
from pathlib import Path
from flask import Blueprint, jsonify

bp = Blueprint('olympus-neural-map', __name__, url_prefix='/api/plugins/olympus-neural-map')

OLIMPO_PATH = Path('/opt/data/memory-map/web/olimpo.json')


@bp.route('/graph', methods=['GET'])
def get_graph():
    """Return the full Monte Olimpo graph for canvas rendering."""
    if not OLIMPO_PATH.exists():
        return jsonify({'error': 'olimpo.json not found', 'path': str(OLIMPO_PATH)}), 404
    
    try:
        with open(OLIMPO_PATH, 'r', encoding='utf-8') as f:
            data = json.load(f)
        return jsonify(data)
    except json.JSONDecodeError as e:
        return jsonify({'error': 'Invalid JSON', 'detail': str(e)}), 500
    except Exception as e:
        return jsonify({'error': 'Failed to read graph', 'detail': str(e)}), 500


@bp.route('/stats', methods=['GET'])
def get_stats():
    """Return summary statistics only (lighter endpoint)."""
    if not OLIMPO_PATH.exists():
        return jsonify({'error': 'olimpo.json not found'}), 404
    
    try:
        with open(OLIMPO_PATH, 'r', encoding='utf-8') as f:
            data = json.load(f)
        
        return jsonify({
            'totais': data.get('totais', {}),
            'gerado': data.get('gerado', 'unknown'),
            'templos_count': len(data.get('templos', [])),
            'deuses_count': len(data.get('deuses', [])),
            'vagalumes_count': len(data.get('vagalumes', []))
        })
    except Exception as e:
        return jsonify({'error': str(e)}), 500


@bp.route('/deus/<nome>', methods=['GET'])
def get_deus(nome):
    """Return details of a specific god/agent."""
    if not OLIMPO_PATH.exists():
        return jsonify({'error': 'olimpo.json not found'}), 404
    
    try:
        with open(OLIMPO_PATH, 'r', encoding='utf-8') as f:
            data = json.load(f)
        
        for deus in data.get('deuses', []):
            if deus.get('nome', '').lower() == nome.lower():
                return jsonify(deus)
        
        return jsonify({'error': f'Deus "{nome}" not found'}), 404
    except Exception as e:
        return jsonify({'error': str(e)}), 500
